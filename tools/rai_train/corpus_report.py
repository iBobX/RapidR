"""Writes tools/rai_train/CORPUS.md: what the last build_corpus.py run made (counts, tokens,
languages, what was left out and why). Small, committed; the data itself is not."""

from __future__ import annotations

import collections
import datetime
import statistics
from pathlib import Path

from rai_corpus import EVAL_RECIPES, HOLDOUT_ADJACENT_RECIPES, META, REPO, row_tokens

KIND_NAMES = {
    "a": "Q&A from the registry (rapidr_describe, then an answer and a program that compiles)",
    "b": "whole programs from a request (the example found or sent, write, check, answer)",
    "c": "error -> fix (a foreign-syntax slip, the compiler's real message, the corrected code)",
    "d": "look first (search_manual / read_file / rapidr_describe before writing)",
    "e": "do not repeat (the same error twice, then look at an example, then fix)",
}
BEGIN = "<!-- validate:begin -->"
END = "<!-- validate:end -->"


def write(b, out: Path, args, pool, notes, secs, n_train, n_valid, with_tokens: bool = True) -> None:
    items = b.items
    by_kind = collections.Counter(i["kind"] for i in items)
    rows_kind = collections.Counter()
    for i in items:
        rows_kind[i["kind"]] += len(i["rows"])
    by_lang = collections.Counter((i["kind"], i["lang"]) for i in items)
    by_prof = collections.Counter((i["kind"], i["profile"]) for i in items)
    tools = collections.Counter(c["function"]["name"] for i in items for m in i["conv"]["messages"] for c in m.get("tool_calls", []))
    toks: dict[str, list[int]] = collections.defaultdict(list)
    if with_tokens:
        try:
            for i in items:
                for r in i["rows"]:
                    toks[i["profile"]].append(row_tokens(r))
        except Exception as e:  # the tokenizer is only in the training venv
            toks.clear()
            print("[corpus] no token counts:", e)
    gens = collections.Counter(i["prov"].get("generator", "").split("+")[-1].split(":")[0] for i in items)
    ver = (META / "rapidr-version.txt").read_text().strip() if (META / "rapidr-version.txt").exists() else "unknown"
    lines = [
        "# RAI training corpus: what the last build made",
        "",
        f"Generated by `tools/rai_train/build_corpus.py` on {datetime.date.today()} (seed {args.seed}, scale {args.scale}{', quick' if args.quick else ''}), "
        f"against `{ver}`. The data is in `$RAI_ROOT/data` (never committed); this file is its report. Every tool answer in the corpus is "
        "the real one of RapidR's own tools (`rai_check` replays them with no model); every program a model is trained to write compiles; "
        "a model's slip shown for context is never learned.",
        "",
        f"**{len(items)} items (conversations), {sum(rows_kind.values())} training rows** ({n_train} train, {n_valid} valid): "
        f"one row per learned assistant turn, because mlx-lm's `--mask-prompt` learns only the last message of a row; {getattr(b, 'dropped_long', 0)} rows longer than {args.max_tokens} tokens were left out ({getattr(b, 'dropped_items', 0)} conversations whose writing turn was that long, whole).",
        "",
        "## Items per kind",
        "",
        "| kind | items | rows | what |",
        "|---|---:|---:|---|",
    ]
    for k in "abcde":
        lines.append(f"| {k} | {by_kind[k]} | {rows_kind[k]} | {KIND_NAMES[k]} |")
    lines += ["", "## Languages and set-ups", "", "| kind | en | es | pt | lite | full | mcp |", "|---|---:|---:|---:|---:|---:|---:|"]
    for k in "abcde":
        lines.append(f"| {k} | " + " | ".join(str(by_lang[(k, l)]) for l in ("en", "es", "pt")) + " | " + " | ".join(str(by_prof[(k, p)]) for p in ("lite", "full", "mcp")) + " |")
    lines += [
        "",
        "Set-ups: `lite` = RAI's instructions and tools for a small window (what a 2B-4B local model gets), `full` = RAI's full set, `mcp` = an outside AI app over Studio's MCP server (its own instructions and 26 tools).",
        "",
        "## Tools called in the conversations",
        "",
        ", ".join(f"`{t}` {n}" for t, n in tools.most_common()),
        "",
    ]
    if toks:
        lines += ["## Tokens per row (Qwen3.5 tokenizer, system prompt and tool schemas included)", "", "| set-up | rows | mean | median | p95 | max |", "|---|---:|---:|---:|---:|---:|"]
        for p in ("lite", "full", "mcp"):
            v = sorted(toks.get(p, []))
            if v:
                lines.append(f"| {p} | {len(v)} | {int(statistics.mean(v))} | {v[len(v) // 2]} | {v[int(len(v) * 0.95) - 1]} | {v[-1]} |")
        lines.append("")
    lines += [
        "## Programs",
        "",
        f"{len(pool)} programs, each compiled by RapidR before use: {sum(1 for p in pool if p.generator == 'real')} real ones from `examples/` and the recipes, "
        f"{sum(1 for p in pool if p.generator.startswith('template'))} from {len({p.generator for p in pool if p.generator.startswith('template')})} templates written for this corpus "
        "(parameters and captions in three languages). Generators: " + ", ".join(f"{g} {n}" for g, n in gens.most_common()) + ".",
        "",
        "## Left out on purpose (hold-out and legal)",
        "",
        f"- The recipes that are the eval's own `apps/` solutions: {', '.join(sorted(EVAL_RECIPES))}. Training on them with the eval's prompts would teach the answers.",
        f"- Recipes topically next to a school task (`school/cpu-emulator`): {', '.join(sorted(HOLDOUT_ADJACENT_RECIPES))}.",
        "- `examples/gui/stopwatch.rr`, `examples/web/todo.rr` (the eval's stopwatch and to-do apps), `examples/rapidq/` (RapidQ-derived), programs over 160 lines, Windows-only programs.",
        "- Everything outside this repository: no RapidQ corpus, no `.reference/`, no cloud-model output (the eval transcripts included), no other project.",
        "- `tests/ai-eval/**` and its reference solutions are the hold-out: `validate_corpus.py` checks every prompt and program against them.",
        "",
        "## Notes of the build",
        "",
        f"Built in {secs:.0f} s. Programs that could not be used: " + ("; ".join(notes[:12]) if notes else "none") + ".",
        "",
        "Candidates dropped while building (reason: count): " + (", ".join(f"{k}: {v}" for k, v in b.rejected.most_common(14)) or "none") + ".",
        "",
        BEGIN,
        "(run `validate_corpus.py` to fill in the validation result)",
        END,
        "",
    ]
    path = REPO / "tools/rai_train/CORPUS.md"
    path.write_text("\n".join(lines))
    print(f"[corpus] wrote {path}")
