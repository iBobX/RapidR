#!/usr/bin/env python3
"""Generate the user manual's reference pages from the source of truth.

    python3 tools/manual_reference.py           write docs/manual/reference/*.md
    python3 tools/manual_reference.py --check   exit 1 if they are out of date

What it reads (nothing is copied by hand):

- components.md: `COMPONENT_TYPES` in crates/rapidr-ast/src/lib.rs (every
  component both compilers create), the RapidQ-name rules of
  `canonical_type_name` (QGAUGE, QOUTLINE, COMPORT), `LIBRARY_TYPES`
  (crates/rapidr-ast/src/library.rs), `INCLUDE_LIBRARY_COMPONENTS`,
  `RAPIDQ_OBJECTS_NOT_YET_IMPLEMENTED` and the preprocessor's
  `RAPIDR_LIBRARIES` (QDIRLISTVIEW, QDOCKFORM);
- builtins.md: `BUILTINS` and `BARE_BUILTINS` in
  interpreter/rapidr-bytecode/src/builtins.rs (the list every runtime's
  dispatch is unit-tested against);
- data-science.md: the `match` arms of RNUM / RDATAFRAME / RPLOT's methods
  and properties in crates/rapidr-runtime-core/src/datascience.rs (desktop:
  native and interpreted) and crates/rapidr-runtime-web/src/datascience_web.rs
  (the web).

The only hand-kept data here are the component categories and RapidQ's own
component list (RC.EXE's built-in names, plus the include libraries'), both
checked against COMPONENT_TYPES so that a new component can't go unlisted:
the script fails and names it.
"""

import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "docs", "manual", "reference")

HEADER = "<!-- Generated by tools/manual_reference.py from {src}. Do not edit: change the source and run the script again. -->\n\n"


def read(rel):
    with open(os.path.join(ROOT, rel), encoding="utf-8") as f:
        return f.read()


def const_list(src, name):
    """The string literals of `pub const NAME: &[&str] = &[ … ];`."""
    m = re.search(r"pub const " + re.escape(name) + r"\s*:\s*&\[[^=]*=\s*&\[(.*?)\];", src, re.S)
    if not m:
        sys.exit(f"manual_reference: {name} not found")
    body = re.sub(r"//[^\n]*", "", m.group(1))
    return re.findall(r'"([^"]*)"', body)


def const_pairs(src, name):
    m = re.search(r"pub const " + re.escape(name) + r"\s*:[^=]*=\s*&\[(.*?)\];", src, re.S)
    if not m:
        sys.exit(f"manual_reference: {name} not found")
    return re.findall(r'\(\s*"([^"]*)"\s*,\s*"([^"]*)"', m.group(1))


